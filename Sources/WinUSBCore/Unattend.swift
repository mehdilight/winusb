import Foundation

/// Rufus-style Windows 11 customisations, implemented through an autounattend.xml
/// placed at the root of the USB drive (Windows Setup picks it up automatically).
public struct UnattendOptions: Equatable {
    /// Bypass TPM 2.0, Secure Boot and 4 GB+ RAM requirements.
    public var bypassHardwareChecks = false
    /// Allow installing without a Microsoft account / internet connection.
    public var bypassOnlineAccount = false
    /// Create a local account with this name (empty = don't).
    public var localAccountName = ""
    /// Answer "no" to all privacy / data-collection questions.
    public var disableDataCollection = false

    public init() {}

    public var isEmpty: Bool {
        !bypassHardwareChecks && !bypassOnlineAccount && !disableDataCollection
            && localAccountName.trimmingCharacters(in: .whitespaces).isEmpty
    }
}

public enum Unattend {
    static let archs = ["amd64", "arm64"]

    static func component(_ name: String, arch: String, body: String) -> String {
        """
            <component name="\(name)" processorArchitecture="\(arch)" publicKeyToken="31bf3856ad364e35" language="neutral" versionScope="nonSxS" xmlns:wcm="http://schemas.microsoft.com/WMIConfig/2002/State" xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance">
        \(body)
            </component>

        """
    }

    static func runSync(_ tag: String, _ commands: [String]) -> String {
        var s = "      <\(tag)s>\n"
        for (i, c) in commands.enumerated() {
            s += """
                    <\(tag) wcm:action="add">
                      <Order>\(i + 1)</Order>
                      <Path>\(escape(c))</Path>
                    </\(tag)>

            """
        }
        return s + "      </\(tag)s>"
    }

    static func escape(_ s: String) -> String {
        s.replacingOccurrences(of: "&", with: "&amp;").replacingOccurrences(of: "<", with: "&lt;")
            .replacingOccurrences(of: ">", with: "&gt;").replacingOccurrences(of: "\"", with: "&quot;")
    }

    public static func xml(_ o: UnattendOptions) -> String? {
        if o.isEmpty { return nil }
        var passes = ""

        if o.bypassHardwareChecks {
            let lab = "reg add HKLM\\SYSTEM\\Setup\\LabConfig /v"
            let cmds = ["BypassTPMCheck", "BypassSecureBootCheck", "BypassRAMCheck", "BypassStorageCheck", "BypassCPUCheck"]
                .map { "\(lab) \($0) /t REG_DWORD /d 1 /f" }
            var body = ""
            for a in archs { body += component("Microsoft-Windows-Setup", arch: a, body: runSync("RunSynchronousCommand", cmds)) }
            passes += "  <settings pass=\"windowsPE\">\n\(body)  </settings>\n"
        }

        if o.bypassOnlineAccount {
            let cmds = ["reg add HKLM\\SOFTWARE\\Microsoft\\Windows\\CurrentVersion\\OOBE /v BypassNRO /t REG_DWORD /d 1 /f"]
            var body = ""
            for a in archs { body += component("Microsoft-Windows-Deployment", arch: a, body: runSync("RunSynchronousCommand", cmds)) }
            passes += "  <settings pass=\"specialize\">\n\(body)  </settings>\n"
        }

        let user = o.localAccountName.trimmingCharacters(in: .whitespaces)
        if !user.isEmpty || o.disableDataCollection || o.bypassOnlineAccount {
            var inner = "      <OOBE>\n"
            if o.disableDataCollection { inner += "        <ProtectYourPC>3</ProtectYourPC>\n" }
            if o.bypassOnlineAccount || !user.isEmpty {
                inner += "        <HideOnlineAccountScreens>true</HideOnlineAccountScreens>\n"
            }
            inner += "      </OOBE>\n"
            if !user.isEmpty {
                let u = escape(user)
                inner += """
                      <UserAccounts>
                        <LocalAccounts>
                          <LocalAccount wcm:action="add">
                            <Name>\(u)</Name>
                            <DisplayName>\(u)</DisplayName>
                            <Group>Administrators;Power Users</Group>
                            <Password>
                              <Value></Value>
                              <PlainText>true</PlainText>
                            </Password>
                          </LocalAccount>
                        </LocalAccounts>
                      </UserAccounts>

                """
            }
            var body = ""
            for a in archs { body += component("Microsoft-Windows-Shell-Setup", arch: a, body: inner) }
            passes += "  <settings pass=\"oobeSystem\">\n\(body)  </settings>\n"
        }

        return """
        <?xml version="1.0" encoding="utf-8"?>
        <!-- Generated by WinUSB for macOS -->
        <unattend xmlns="urn:schemas-microsoft-com:unattend">
        \(passes)</unattend>

        """
    }
}
